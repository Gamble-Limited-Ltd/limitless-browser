#!/usr/bin/env python3
"""Fetch the Limitless Browser fonts (SIL OFL) from Google Fonts as latin woff2 files.

Writes theme/fonts/<slug>/*.woff2, theme/fonts/<slug>/OFL.txt and theme/fonts.css.
Run once, commit the output. The app never calls Google Fonts at runtime.
Usage: python3 scripts/fetch-fonts.py [output-root]   (default: repo root)
"""
import re, sys, urllib.request, urllib.parse, pathlib

UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent)
OUT = ROOT / "theme" / "fonts"

# (family, google css2 spec, google/fonts repo dir for OFL.txt)
FAMILIES = [
    ("Bodoni Moda", "Bodoni+Moda:wght@400..600", "bodonimoda"),
    ("Jost", "Jost:wght@300..500", "jost"),
    ("Fraunces", "Fraunces:ital,wght@0,400..700;1,400..700", "fraunces"),
    ("Outfit", "Outfit:wght@300..600", "outfit"),
    ("Figtree", "Figtree:wght@300..600", "figtree"),
    ("Quicksand", "Quicksand:wght@400..700", "quicksand"),
    ("Nunito", "Nunito:wght@400..700", "nunito"),
    ("VT323", "VT323", "vt323"),
    ("IBM Plex Mono", "IBM+Plex+Mono:wght@400;500", "ibmplexmono"),
    ("Playfair Display", "Playfair+Display:wght@400..700", "playfairdisplay"),
    ("DM Sans", "DM+Sans:wght@400..600", "dmsans"),
    ("DM Mono", "DM+Mono:wght@300;400;500", "dmmono"),
]

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()

css_out = ["/* Self-hosted fonts (SIL OFL 1.1). Generated by scripts/fetch-fonts.py. Latin subset. */"]
for family, spec, repo in FAMILIES:
    slug = repo
    css = get("https://fonts.googleapis.com/css2?family=%s&display=swap" % spec).decode()
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
    latin = [b for sub, b in blocks if sub == "latin"]
    if not latin:
        raise SystemExit("no latin block for " + family)
    d = OUT / slug
    d.mkdir(parents=True, exist_ok=True)
    for i, b in enumerate(latin):
        url = re.search(r"url\((https://[^)]+\.woff2)\)", b).group(1)
        style = re.search(r"font-style:\s*(\w+)", b).group(1)
        weight = re.search(r"font-weight:\s*([\d ]+);", b).group(1).strip()
        wtag = weight.replace(" ", "-")
        fname = "%s-%s-%s.woff2" % (slug, style, wtag)
        data = get(url)
        if data[:4] != b"wOF2":
            raise SystemExit("not woff2: " + url)
        (d / fname).write_bytes(data)
        urange = re.search(r"unicode-range:\s*([^;]+);", b).group(1).strip()
        css_out.append(
            "@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:swap;"
            "src:url(fonts/%s/%s) format('woff2');unicode-range:%s}" % (family, style, weight, slug, fname, urange)
        )
    ofl = get("https://raw.githubusercontent.com/google/fonts/main/ofl/%s/OFL.txt" % repo)
    (d / "OFL.txt").write_bytes(ofl)
    print(family, "ok", len(latin), "files")
(ROOT / "theme" / "fonts.css").write_text("\n".join(css_out) + "\n")
